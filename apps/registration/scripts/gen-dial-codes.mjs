// Generates src/lib/dialCodes.ts from libphonenumber-js metadata.
//
// Why generate instead of importing libphonenumber-js in the app: the flow has
// to load on a phone on Tanzanian mobile data, and the full metadata is ~145KB.
// All we actually need is, per country, the dial code and which national-number
// lengths are possible. That is a few KB, and it comes from Google's libphonenumber
// data rather than a hand-typed list.
import { writeFileSync } from 'node:fs';
import {
  getCountries, getCountryCallingCode, getExampleNumber, validatePhoneNumberLength,
} from 'libphonenumber-js';
import { createRequire } from 'node:module';
const require_ = createRequire(import.meta.url);
const examples = require_('libphonenumber-js/examples.mobile.json');

// Length validation is prefix-independent, so probing every length from 3 to 15
// with a filler digit recovers the exact set of possible lengths.
function possibleLengths(cc) {
  const out = [];
  for (let len = 3; len <= 15; len++) {
    if (validatePhoneNumberLength('4'.repeat(len), cc) === undefined) out.push(len);
  }
  return out;
}

const names = new Intl.DisplayNames(['en'], { type: 'region' });

const rows = [];
for (const cc of getCountries()) {
  const lens = possibleLengths(cc);
  if (!lens.length) continue;
  const example = getExampleNumber(cc, examples);
  rows.push({
    cc,
    dial: '+' + getCountryCallingCode(cc),
    name: names.of(cc) ?? cc,
    len: lens,
    ex: example ? example.nationalNumber : '',
  });
}

rows.sort((a, b) => a.name.localeCompare(b.name));

const body = rows
  .map(r => `  { cc: '${r.cc}', dial: '${r.dial}', name: ${JSON.stringify(r.name)}, len: [${r.len}], ex: '${r.ex}' },`)
  .join('\n');

writeFileSync(
  new URL('../src/lib/dialCodes.ts', import.meta.url),
  `// GENERATED by scripts/gen-dial-codes.mjs from libphonenumber-js. Do not edit.
// Run \`npm run gen:dials\` to refresh.
//
// len is the set of valid national-number lengths for that country, so the
// validator is per-country rather than one global "at least 7 digits" guess.

export type DialCode = {
  /** ISO 3166-1 alpha-2, also used to build the flag. */
  cc: string;
  dial: string;
  name: string;
  /** Valid national-number lengths. */
  len: number[];
  /** A real example number, used for the placeholder. */
  ex: string;
};

export const DIAL_CODES: DialCode[] = [
${body}
];

export const DIAL_BY_CC: Record<string, DialCode> =
  Object.fromEntries(DIAL_CODES.map(d => [d.cc, d]));
`,
);

console.log(`wrote ${rows.length} countries`);
