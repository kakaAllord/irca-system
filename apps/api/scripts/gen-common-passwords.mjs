// Regenerates src/core/auth/common-passwords.ts from the UK NCSC's list of the
// 100,000 passwords most often seen in breaches (published via SecLists).
//
// Only entries of PASSWORD_MIN (10) characters or more are kept: shorter ones
// are already refused by the length rule, so listing them adds weight and
// catches nothing.
//
//   node apps/api/scripts/gen-common-passwords.mjs            (downloads the list)
//   node apps/api/scripts/gen-common-passwords.mjs list.txt   (uses a file you downloaded,
//                                                             e.g. behind a proxy Node ignores)
import { readFileSync, writeFileSync } from 'node:fs';

const SOURCE =
  'https://raw.githubusercontent.com/danielmiessler/SecLists/master/Passwords/Common-Credentials/100k-most-used-passwords-NCSC.txt';
const MIN = 10;
const MAX = 128;

const text = process.argv[2]
  ? readFileSync(process.argv[2], 'utf8')
  : await (await fetch(SOURCE)).text();
const words = [
  ...new Set(
    text
      .split(/\r?\n/)
      .map((w) => w.trim().toLowerCase())
      .filter((w) => w.length >= MIN && w.length <= MAX),
  ),
].sort();

const out = `// Generated by scripts/gen-common-passwords.mjs. Do not edit by hand.
// Source: ${SOURCE}
// ${words.length} entries of ${MIN}-${MAX} characters, lowercased.
export const COMMON_PASSWORDS_TEXT = ${JSON.stringify(words.join('\n'))};
`;
writeFileSync(new URL('../src/core/auth/common-passwords.ts', import.meta.url), out);
// eslint-disable-next-line no-console -- a CLI script reports to its terminal
console.log(`wrote ${words.length} entries`);
